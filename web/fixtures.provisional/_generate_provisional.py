"""Generate PROVISIONAL fixtures for the Wattson web app.

Reshapes data the pipeline already exports (dashboard/public/data/regions.json,
heatmaps, alerts.json), the mock company file (claims/companies.mock.json) and
the hand-mapped operator table (scripts/operators_manual.json) into the shapes
the future API will return. Yash's fixtures/{region,site,company}.json (and then
the API) replace these. Stdlib only; run from anywhere.

    python3 fixtures/_generate_provisional.py
"""
