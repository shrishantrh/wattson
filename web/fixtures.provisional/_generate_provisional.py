def load(rel):
    with open(os.path.join(REPO, rel)) as f:
        return json.load(f)


def dump(obj, name, **kw):
    path = os.path.join(HERE, name)
    with open(path, "w") as f:
        json.dump(obj, f, allow_nan=False, **kw)
    return path, os.path.getsize(path)


def header():
    return {"_provisional": True, "_generated": GENERATED, "_note": NOTE}


def yr(d, y):
    return (d or {}).get(str(y))


# --------------------------------------------------------------------------
def main():
    data = load("dashboard/public/data/regions.json")
    meta, regions = data["meta"], data["regions"]
    by_id = {r["id"]: r for r in regions}
    alerts_doc = load("dashboard/public/data/alerts.json")
    ops_manual = load("scripts/operators_manual.json")
    mock = load("claims/companies.mock.json")

    missing = [m[1] for m in METRO_INDEX if m[1] not in by_id]
    if missing:
        sys.exit(f"metro index maps to unknown region ids: {missing}")
    for rid in REGION_IDS:
        if rid not in by_id:
            sys.exit(f"unknown region id in REGION_IDS: {rid}")

    def parent_of(r):
        return by_id[r["ba"]] if r["type"] == "zone" else None

    def siting_of(r):
        # Zones inherit the parent BA's generation figures, so siting comes
        # from the parent (identical in regions.json, but be explicit).
        p = parent_of(r)
        src = p if p is not None else r
        return src["siting"], src["id"]

    # ---------------------------------------------------------------- opening
    pjm, dom = by_id["PJM"], by_id["PJM/DOM"]
    years = ("2019", "2025")

    def two(d, key=None):
        out = {}
        for y in years:
            v = yr(d, y)
            out[y] = (v.get(key) if (key and v is not None) else v)
        return out

    pjm_block = {
        "overnight_clean_mw": two(pjm["cf_avg_mw"], "overnight"),
        "overnight_total_mw": two(pjm["total_avg_mw"], "overnight"),
        "overnight_cf_share": two(pjm["cf_share"], "overnight"),
        "overnight_net_export_mw": {
            **two(pjm["interchange"], "overnight_net_export_mw"),
            "sign": "positive = export",
            "source": "EIA-adjusted operations table; partner-level table unreliable for PJM before 2020",
        },
        "fuel_delta_overnight_gw": pjm["fuel_delta_overnight_gw"],
        "dom_overnight_demand_mw": two(dom["demand"], "overnight_avg_mw"),
        "dom_avg_demand_mw": two(dom["demand"], "avg_mw"),
        "profile_24h": pjm.get("profile_24h"),
        "overnight_fuel_mw": pjm.get("overnight_fuel_mw"),
        "cf_share": pjm.get("cf_share"),
        "cf_avg_mw": pjm.get("cf_avg_mw"),
        "total_avg_mw": pjm.get("total_avg_mw")
    }

    flagged_ids = set(meta["data_flags"].keys())
    validation_ids = set(meta["detector"]["validation_named_in_advance"])
    scored = sorted((r for r in regions if r.get("detection")),
                    key=lambda r: r["detection"]["rank"])
    det_rows = []
    for r in scored:
        d = r["detection"]
        cf25 = yr(r["cf_share"], 2025)
        dm25 = yr(r["demand"], 2025)
        det_rows.append({
            "id": r["id"], "ba": r["ba"], "zone": r["zone"], "type": r["type"],
            "name": r["name"], "ba_name": r["ba_name"],
            "rank": d["rank"], "score": d["score"], "pattern": d["pattern"],
            "growth_pct": d["growth_pct"],
            "overnight_excess": d["overnight_excess"],
            "neighbor_divergence": d["neighbor_divergence"],
            "load_factor_delta": d["load_factor_delta"],
            "avg_mw_2025": dm25.get("avg_mw") if dm25 else None,
            "overnight_cf_share_2025": cf25.get("overnight") if cf25 else None,
            "data_flagged": r["id"] in flagged_ids,
            "validation": r["id"] in validation_ids,
            "known_cluster_label": KNOWN_CLUSTERS.get(r["id"]),
        })
    # Top-10 flat-load regions not named in advance and not data-flagged; a parent grid is not a
    # separate lead when one of its own zones already is (ERCOT when N. Texas leads).
    cand = [row for row in det_rows
            if row["rank"] <= 10 and row["id"] not in KNOWN_CLUSTERS
            and not row["data_flagged"] and row.get("pattern") == "flat-load growth"]
    ids = {row["id"] for row in cand}
    new_leads = [row["id"] for row in cand
                 if "/" in row["id"] or not any(x.startswith(row["id"] + "/") for x in ids)]

    opening = {
        **header(),
        "headline": meta["headline"],
        "data_snapshot_end": meta["data_snapshot_end"],
        "baseline_year": meta["baseline_year"],
        "overnight_hours_local": meta["overnight_hours_local"],
        "daytime_hours_local": meta["daytime_hours_local"],
        "pjm": pjm_block,
        "national": {"cf_share": meta["national"]["cf_share"],
                     "cf_avg_mw": meta["national"]["cf_avg_mw"]},
        "detector": {
            "n_scored": meta["detector"]["n_scored"],
            "method": meta["detector"]["method"],
            "validation_named_in_advance": meta["detector"]["validation_named_in_advance"],
            "known_clusters": KNOWN_CLUSTERS,
            "new_leads": new_leads,
            "regions": det_rows,
        },
        "caveats": meta["caveats"],
        "pattern_labels": meta["pattern_labels"],
        "data_flags": meta["data_flags"],
    }

    # ----------------------------------------------------------------- region
    heat_cache = {}

    def heatmap_for(r):
        uri = r["heatmap_uri"]
        if uri not in heat_cache:
            with open(os.path.join(PUB, uri)) as f:
                heat_cache[uri] = json.load(f)
        return heat_cache[uri]

    region_out = {}
    for rid in REGION_IDS:
        r = copy.deepcopy(by_id[rid])
        p = parent_of(r)
        r["parent"] = copy.deepcopy(p) if p is not None else None
        r["heatmap"] = copy.deepcopy(heatmap_for(by_id[rid]))
        r["operators_manual"] = ops_manual.get(rid, [])
        r["alerts"] = [a for a in alerts_doc["alerts"] if a.get("region") == rid]
        region_out[rid] = r
    region = {**header(),
              "alerts_meta": {"generated": alerts_doc["generated"],
                              "latest_month": alerts_doc["latest_month"],
                              "rules": alerts_doc["rules"],
                              "excluded_regions": alerts_doc["excluded_regions"]},
              "regions": region_out}

    # ------------------------------------------------------------------- site
    metro_rows = [{"metro": m, "region_id": rid, "ba": by_id[rid]["ba"],
                   "zone": by_id[rid]["zone"], "lat": lat, "lng": lng,
                   "serving_utility": su}
                  for (m, rid, lat, lng, su) in METRO_INDEX]
    metro_by_name = {m["metro"]: m for m in metro_rows}

    def largest_positive(fd):
        best = None
        for fuel, v in (fd or {}).items():
            if v is not None and v > 0 and (best is None or v > best[1]):
                best = (fuel, v)
        return {"fuel": best[0], "delta_gw": best[1]} if best else {"fuel": None, "delta_gw": None}

    results = []
    for cand in SITE_REQUEST["candidates"]:
        m = metro_by_name[cand]
        r = by_id[m["region_id"]]
        siting, siting_from = siting_of(r)
        ops = ops_manual.get(r["id"], [])
        d = r.get("detection") or {}
        results.append({
            "metro": cand, "region_id": r["id"], "ba": r["ba"], "zone": r["zone"],
            "cf_inherited_from_ba": r["cf_inherited_from_ba"],
            "serving_utility": ops[0]["utility"] if ops else m["serving_utility"],
            "operators": ops,
            "siting": siting,
            "siting_from": siting_from,
            "fuel_delta_overnight_gw": r["fuel_delta_overnight_gw"],
            "last_growth_filled_by": largest_positive(r["fuel_delta_overnight_gw"]),
            "overnight_fuel_mw_2025": yr(r["overnight_fuel_mw"], 2025),
            "detector": {"rank": d.get("rank"), "score": d.get("score"),
                         "pattern": d.get("pattern"), "growth_pct": d.get("growth_pct")},
            "demand": yr(r["demand"], 2025),
            "headroom_note": "no capacity headroom claimed; slope only",
            "lat": m["lat"], "lng": m["lng"],
        })
    results.sort(key=lambda x: -(x["siting"]["siting_score"] if x["siting"]["siting_score"] is not None else -1e9))
    for i, x in enumerate(results, 1):
        x["rank"] = i
    site = {**header(),
            "request": SITE_REQUEST,
            "metro_index": {"hand_mapped": True,
                            "note": "Hand-mapped metro -> region id; lat/lng are approximate metro centroids, not from the data.",
                            "metros": metro_rows},
            "ranking_key": "siting.siting_score (higher = cleaner); zones use the parent BA's siting",
            "results": results,
            "caveats": meta["caveats"]}

    # ---------------------------------------------------------------- company
    companies = {}
    for c in mock:
        c = copy.deepcopy(c)
        for s in c["sites"]:
            s["zone"] = s.get("pjm_zone")
            s["region_id"] = f'{s["ba"]}/{s["zone"]}' if s["zone"] else s["ba"]
            if s["region_id"] not in by_id:
                sys.exit(f"company site maps to unknown region id: {s['region_id']}")
            lat, lng = SITE_COORDS.get(s["metro"], (None, None))
            s["lat"], s["lng"] = lat, lng
        counts = {}
        for cl in c["claims"]:
            counts[cl["verdict"]] = counts.get(cl["verdict"], 0) + 1
            for e in cl.get("evidence", []):
                if e.get("type") == "grid":
                    reg = by_id.get(e["ba"])
                    cf = yr(reg["cf_share"], e["year"]) if reg else None
                    e["overnight_cf_share"] = cf.get("overnight") if cf else None
        c["verdict_counts"] = counts
        c["cannot_verify_count"] = counts.get("cannot_verify", 0)
        companies[c["ticker"]] = c
    company = {**header(), "companies": companies}

    # ------------------------------------------------------------------ write
    sizes = {}
    for name, obj in (("opening.json", opening), ("site.json", site), ("company.json", company)):
        sizes[name] = dump(obj, name, indent=1)
    path, n = dump(region, "region.json", indent=1)
    if n > 3_000_000:
        path, n = dump(region, "region.json", separators=(",", ":"))
    if n > 3_000_000:
        for r in region["regions"].values():
            r["heatmap"]["cf_share"] = [[None if v is None else round(v, 3) for v in row]
                                        for row in r["heatmap"]["cf_share"]]
        path, n = dump(region, "region.json", separators=(",", ":"))
    sizes["region.json"] = (path, n)

    for name, (path, n) in sizes.items():
        print(f"{name:14s} {n/1e6:6.2f} MB  {path}")
    print("new_leads:", new_leads)
    print("site ranking:", [(x["rank"], x["metro"], x["region_id"], x["siting"]["siting_score"]) for x in results])


if __name__ == "__main__":
    main()
